"""Generate docker-compose.yml from the topology in ftuni/config.py (single source of truth).

    python deploy/make_compose.py > docker-compose.yml

Design:
* one container per instance, same image, `init: true` (tini as PID 1), restart: always
* node B replicas are in the "replicas" profile: the baseline runs node A only
* network segmentation: `app` (gateway <-> services), `data` (services <-> database),
  `bank` (payment <-> external bank), `ops` (monitoring). Only the gateway, Grafana,
  Prometheus and Alertmanager publish ports, and only on 127.0.0.1.
* hardening: non-root user (image), read-only root filesystem, no capabilities,
  no-new-privileges, CPU and memory limits
* secrets are files mounted under /run/secrets, each container gets only its own
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from ftuni import config  # noqa: E402

NETWORKS = {"gateway": ["app"], "monitor": ["app", "data", "bank"], "bank": ["bank"], "db": ["data"],
            "student": ["app", "data"], "payment": ["app", "data", "bank"], "records": ["app", "data"],
            "timetable": ["app"]}
CPUS = {"gateway": 1.0, "db": 1.0}
MEM = {"db": "512m", "gateway": "384m"}
SECRETS = {   # source secret -> file name inside /run/secrets
    "gateway": [("jwt_key", "jwt_key"), ("ops_token", "ops_token"), ("users", "users.json")],
    "monitor": [("db_token_monitor", "db_token"), ("ops_token", "ops_token")],
    "db": [("db_token_peer", "db_token"), ("db_token_student", "db_token_student"),
           ("db_token_payment", "db_token_payment"), ("db_token_records", "db_token_records"),
           ("db_token_monitor", "db_token_monitor"), ("ops_token", "ops_token")],
    "student": [("db_token_student", "db_token"), ("ops_token", "ops_token")],
    "payment": [("db_token_payment", "db_token"), ("ops_token", "ops_token")],
    "records": [("db_token_records", "db_token"), ("ops_token", "ops_token")],
    "timetable": [("ops_token", "ops_token")],
    "bank": [("ops_token", "ops_token")],
}
ALL_SECRETS = ["jwt_key", "ops_token", "users", "db_token_peer", "db_token_student", "db_token_payment",
               "db_token_records", "db_token_monitor", "grafana_admin"]
SECRET_FILES = {"users": "users.json"}

ENV = '''      FTUNI_DOCKER: "1"
      FTUNI_MODE: "${FTUNI_MODE:-endterm}"
      FTUNI_RUN_DIR: /app/run'''


def service(i: config.Instance) -> str:
    secrets = "\n".join(f"      - {{source: {s}, target: {t}}}" for s, t in SECRETS[i.kind])
    nets = "\n".join(f"      - {n}" for n in NETWORKS[i.kind])
    profile = '\n    profiles: ["replicas"]' if i.node == "B" else ""
    ports = '\n    ports: ["127.0.0.1:8000:8000"]' if i.kind == "gateway" else ""
    return f'''
  {i.name}:
    <<: *app
    container_name: ftuni-{i.name}
    hostname: {i.name}
    command: ["{i.name}"]{profile}{ports}
    cpus: {CPUS.get(i.kind, 0.5)}
    mem_limit: {MEM.get(i.kind, "256m")}
    labels: {{ftuni.kind: "{i.kind}", ftuni.node: "{i.node}"}}
    environment:
{ENV}
      FTUNI_PORT: "{i.port}"
    networks:
{nets}
    secrets:
{secrets}'''


def main() -> None:
    out = ['''# Generated by deploy/make_compose.py from ftuni/config.py - do not edit by hand.
#   FTUNI_MODE=endterm COMPOSE_PROFILES=replicas docker compose up -d     (endterm build)
#   FTUNI_MODE=ft      COMPOSE_PROFILES=replicas docker compose up -d     (midterm FT build)
#   FTUNI_MODE=baseline                          docker compose up -d     (midterm baseline)
name: ftuni

x-app: &app
  image: ftuni:endterm
  build: .
  init: true
  restart: always
  read_only: true
  tmpfs: [/tmp]
  cap_drop: [ALL]
  security_opt: ["no-new-privileges:true"]
  volumes: ["./run-docker:/app/run"]
  depends_on:
    init: {condition: service_completed_successfully}
  healthcheck:
    test: ["CMD", "/app/deploy/healthcheck.sh"]
    interval: 5s
    timeout: 3s
    retries: 3
    start_period: 20s
  logging:
    driver: json-file
    options: {max-size: "20m", max-file: "2"}

services:
  init:
    image: ftuni:endterm
    entrypoint: ["python", "-m", "ftuni.dockerinit"]
    restart: "no"
    network_mode: none
    read_only: true
    environment:
''' + ENV + '''
    volumes: ["./run-docker:/app/run"]''']
    for i in config.topology("ft"):
        out.append(service(i))
    out.append('''
  alert-sink:
    <<: *app
    container_name: ftuni-alert-sink
    entrypoint: ["python", "-m", "ftuni.alertsink"]
    command: []
    healthcheck: {disable: true}
    cpus: 0.25
    mem_limit: 128m
    environment:
''' + ENV + '''
    networks: [ops]

  prometheus:
    image: prom/prometheus:v2.54.1
    container_name: ftuni-prometheus
    restart: always
    command: ["--config.file=/etc/prometheus/prometheus.yml", "--storage.tsdb.retention.time=6h",
              "--web.enable-lifecycle"]
    depends_on:
      init: {condition: service_completed_successfully}
    volumes:
      - ./deploy/prometheus/prometheus.yml:/etc/prometheus/prometheus.yml:ro
      - ./deploy/prometheus/alerts.yml:/etc/prometheus/alerts.yml:ro
      - ./run-docker/prometheus:/etc/prometheus/targets:ro
    secrets: [{source: ops_token, target: ops_token}]
    ports: ["127.0.0.1:9090:9090"]
    cpus: 1.0
    mem_limit: 512m
    networks: [app, data, bank, ops]

  alertmanager:
    image: prom/alertmanager:v0.27.0
    container_name: ftuni-alertmanager
    restart: always
    volumes: ["./deploy/alertmanager/alertmanager.yml:/etc/alertmanager/alertmanager.yml:ro"]
    ports: ["127.0.0.1:9093:9093"]
    cpus: 0.25
    mem_limit: 128m
    networks: [ops]

  grafana:
    image: grafana/grafana:11.2.0
    container_name: ftuni-grafana
    restart: always
    environment:
      GF_AUTH_ANONYMOUS_ENABLED: "true"
      GF_AUTH_ANONYMOUS_ORG_ROLE: Viewer
      GF_SECURITY_ADMIN_PASSWORD__FILE: /run/secrets/grafana_admin
      GF_DASHBOARDS_DEFAULT_HOME_DASHBOARD_PATH: /var/lib/grafana/dashboards/ftuni.json
      GF_ANALYTICS_REPORTING_ENABLED: "false"
      GF_ANALYTICS_CHECK_FOR_UPDATES: "false"
    volumes:
      - ./deploy/grafana/provisioning:/etc/grafana/provisioning:ro
      - ./deploy/grafana/dashboards:/var/lib/grafana/dashboards:ro
    secrets: [{source: grafana_admin, target: grafana_admin}]
    ports: ["127.0.0.1:3000:3000"]
    cpus: 0.5
    mem_limit: 256m
    networks: [ops]

networks:
  app: {}
  data: {internal: true}
  bank: {internal: true}
  ops: {}

secrets:''')
    for s in ALL_SECRETS:
        out.append(f"  {s}: {{file: ./deploy/secrets/{SECRET_FILES.get(s, s)}}}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
